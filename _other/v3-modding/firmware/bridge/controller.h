#ifndef MICROSMT_BRIDGE_CONTROLLER_H
#define MICROSMT_BRIDGE_CONTROLLER_H
#include "bus_packet.h"

#define BRIDGE_RESPONSE_MS 150u
#define BRIDGE_LINE_SIZE 64u
typedef struct {
    uint32_t framing, overrun, collision, timing;
} bridge_stats_t;
typedef struct {
    void *context;
    bool (*send)(void *context, const uint8_t frame[BUS_FRAME_SIZE]);
    void (*cancel)(void *context);
    void (*emit)(void *context, const char *line);
} bridge_io_t;
typedef struct {
    bridge_io_t io;
    bus_parser_t parser;
    bus_packet_t pending;
    bridge_stats_t stats, baseline;
    uint32_t started, next_transaction;
    uint16_t scan_next, scan_end, found, missing;
    bool active, scanning, raw, discard;
    char line[BRIDGE_LINE_SIZE];
    unsigned length;
} bridge_controller_t;

/* Single main-context owner. Call poll before processing received bytes/commands.
 * IO callbacks must be bounded; cancel releases the wire and flushes queued RX.
 * Disconnect resets all session state except counters/transaction allocation.
 * No motion commands are generated by the readable diagnostic interface. */
void bridge_init(bridge_controller_t *b, bridge_io_t io);
void bridge_disconnect(bridge_controller_t *b);
void bridge_poll(bridge_controller_t *b, uint32_t now, bridge_stats_t stats);
void bridge_input(bridge_controller_t *b, uint8_t ch, uint32_t now);
void bridge_receive(bridge_controller_t *b, uint8_t byte, uint32_t now);
#endif
